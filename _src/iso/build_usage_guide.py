def frame(no, body):
    return ('<section class="pg"><div class="run">ISO 기록 도구 사용 안내 | %s</div>%s'
            '<div class="ft">동인엔시스 | %s | 페이지 %d / 전체 %d</div></section>' % (DOC, body, DOC, no, TOTAL))


def page(title, target, body, no):
    return frame(no, '%s<h1>%s</h1><p class="docline">%s · 대상: %s</p>%s' % (logo_tag(), E(title), E(DOCLINE), E(target), body))


def shot(name, cap, width):
    return ('<figure class="shot" style="width:%s"><img src="shots/%s.jpg" alt="%s"><figcaption>%s</figcaption></figure>'
            % (width, name, E(cap), E(cap)))


def steps(rows, start=1):
    """[(제목, 설명)] → 번호 붙은 절차 표. 「」 안은 화면의 버튼·칸 이름."""
    tr = ''.join('<tr><td class="n">%d</td><td><b>%s</b><br>%s</td></tr>' % (start + k, E(a), E(b)) for k, (a, b) in enumerate(rows))
    return '<table class="tbl steps"><colgroup><col style="width:8mm"><col></colgroup><tbody>%s</tbody></table>' % tr


def note(t):
    return '<p class="note">%s</p>' % E(t)


